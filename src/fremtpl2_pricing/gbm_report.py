"""Render ``reports/gbm_cv.md`` from the ``results/cv_gbm.json`` payload (no hand-typed numbers)."""

from __future__ import annotations

from typing import Any


def _f(x: Any, nd: int = 5) -> str:
    return "n/a" if x is None else f"{x:.{nd}f}"


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    return [_row(header), _row(["---"] * len(header)), *(_row(r) for r in rows), ""]


def _grid(block: dict[str, Any]) -> list[str]:
    rows = []
    for i, p in enumerate(block["grid"]):
        hp = ", ".join(f"{k}={v}" for k, v in sorted(p["hp"].items()))
        mark = " (chosen)" if i == block["chosen_index"] else ""
        rows.append(
            [
                f"{i}{mark}",
                hp,
                _f(p["mean_loss"], 6),
                ", ".join(str(b) for b in p["fold_best_iteration"]),
                str(p["rounds"]),
                "yes" if any(p["fold_cap_reached"]) else "no",
            ]
        )
    return _table(
        [
            "#",
            "hyperparameters",
            "mean CV loss",
            "best iteration per fold",
            "rounds",
            "cap reached",
        ],
        rows,
    )


def _stat(s: dict[str, Any]) -> str:
    return f"mean {_f(s['mean'], 6)}, sd {_f(s['sd'], 6)}"


def render_report(res: dict[str, Any]) -> str:
    cfg = res["config"]
    out = [
        "# GBM cross-validation (milestone 3, train only)",
        "",
        "Generated by `fremtpl2 gbm` from `results/cv_gbm.json`. " + cfg["scores_label"] + ".",
        "",
        f"Tweedie power (read from `results/cv_glm.json`): {cfg['tweedie_power']}; "
        f"primary-loss reference power: {cfg['reference_power']}; folds: {cfg['cv_folds']}.",
        "",
        "## Tuning (optimistic tuning scores)",
        "",
    ]
    for comp, block in res["components"].items():
        out += [
            f"### {comp}",
            "",
            f"Chosen: #{block['chosen_index']}, rounds {block['rounds']}, cap reached in a fold of "
            f"the chosen point: {block['cap_reached_any_fold']}.",
            "",
            *_grid(block),
        ]
    k = len(res["oof"]["per_fold"])
    pp = [PP for PP in res["oof"]["per_fold"][0]["pure_premium"]]
    out += ["## Out-of-fold pure premium (chosen settings)", ""]
    rows = []
    for name in pp:
        losses = [f["pure_premium"][name]["primary_loss"] for f in res["oof"]["per_fold"]]
        s = res["oof"]["summary"]["pure_premium"][name]
        rows.append(
            [
                name,
                ", ".join(_f(x, 6) for x in losses),
                _f(s["primary_loss"]["mean"], 6),
                _f(s["gini_normalized"]["mean"], 4),
                _f(s["totals"]["ratio"]["mean"], 4),
            ]
        )
    out += _table(
        ["candidate", f"primary loss per fold (K={k})", "mean", "normalised Gini", "obs/pred"], rows
    )
    sel = res["selection"]["gbm_pure_premium"]
    st = sel["steps"][0]
    out += [
        "## Selection of the GBM pure-premium candidate (protocol section 4, step 6)",
        "",
        f"Rule `{sel['rule_version']}`: mean d = {_f(st['mean_d'], 6)}, sd/sqrt(K) = "
        f"{_f(st['threshold'], 6)}; selected **{res['selection']['selected']}** ({st['reason']}).",
        "",
        "## Frequency and severity components (out of fold)",
        "",
    ]
    s = res["oof"]["summary"]
    out += [
        f"- Poisson deviance per exposure: "
        f"{_stat(s['frequency']['poisson_deviance_per_exposure'])}; "
        f"normalised Gini {_f(s['frequency']['gini_normalized']['mean'], 4)}",
        f"- Gamma deviance per claim: {_stat(s['severity']['gamma_deviance_per_claim'])}",
        "",
    ]
    diag = res.get("diagnostic")
    if diag:
        out += ["## Monotonicity diagnostic (CV only, not a candidate, feeds no selection)", ""]
        sep = diag["separately_tuned"]
        out += ["### Separately tuned procedures", ""]
        for comp in ("frequency", "tweedie"):
            if comp in sep:
                d = sep[comp]["component_loss_diff_unconstrained_minus_constrained"]
                out.append(
                    f"- {comp}: component deviance, unconstrained minus constrained: {_stat(d)}; "
                    f"constrained {sep[comp]['constrained']['hp']} / "
                    f"{sep[comp]['constrained']['rounds']} "
                    f"rounds, unconstrained {sep[comp]['unconstrained']['hp']} / "
                    f"{sep[comp]['unconstrained']['rounds']} rounds"
                )
        pl = sep["primary_loss"]
        out += [
            f"- primary loss, freq x sev, unconstrained minus constrained: "
            f"{_stat(pl['diff_freq_x_sev_unconstrained_minus_constrained'])}",
            f"- primary loss, Tweedie, unconstrained minus constrained: "
            f"{_stat(pl['diff_tweedie_unconstrained_minus_constrained'])}",
            "",
            "### Controlled ablation (chosen hyperparameters and rounds, constraint toggled)",
            "",
        ]
        for comp, row in diag["ablation"].items():
            comp_d = _stat(row["component_loss_diff_unconstrained_minus_constrained"])
            prim_d = _stat(row["primary_loss_diff_unconstrained_minus_constrained"])
            out.append(
                f"- {comp} ({row['rounds']} rounds): component deviance diff {comp_d}; "
                f"primary loss diff {prim_d}"
            )
        out.append("")
    t = res["timing_seconds"]
    out += ["## Checks and timings", ""]
    out += [f"- {k}: {v}" for k, v in res["checks"].items() if k != "passed"]
    out += [f"- passed: {res['checks']['passed']}", ""]
    out += [f"- {k}: {_f(v, 1)} s" for k, v in t.items()]
    out.append("")
    return "\n".join(out)
